-- Se a tabela já existe, dropar para recriar com todos os campos
DROP TABLE IF EXISTS pendencias CASCADE;

-- Criar tabela de pendências com TODOS os campos necessários
CREATE TABLE pendencias (
    -- Identificadores
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    materia_id BIGINT NOT NULL REFERENCES materia(id) ON DELETE CASCADE,
    avaliacao_id BIGINT REFERENCES avaliacao(id) ON DELETE CASCADE,

    -- Status de Pendências - MATÉRIAS
    status_criacao_avaliacao VARCHAR(20) CHECK (status_criacao_avaliacao IN ('PENDENTE', NULL)),
    status_plano_aula VARCHAR(20) CHECK (status_plano_aula IN ('PENDENTE', NULL)),
    status_plano_ensino VARCHAR(20) CHECK (status_plano_ensino IN ('PENDENTE', NULL)),

    -- Status de Pendências - AVALIAÇÕES
    status_avaliacao VARCHAR(20) CHECK (status_avaliacao IN ('PENDENTE', NULL)),
    status_gabarito VARCHAR(20) CHECK (status_gabarito IN ('PENDENTE', NULL)),
    status_revisao VARCHAR(20) CHECK (status_revisao IN ('PENDENTE', NULL)),
    status_cadastro_sgn VARCHAR(20) CHECK (status_cadastro_sgn IN ('PENDENTE', NULL)),
    acompanhamento_pedagogico_sgn VARCHAR(20) CHECK (acompanhamento_pedagogico_sgn IN ('PENDENTE', NULL)),

    -- Campos adicionais do formulário (usados por dashboard.html)
    descricao TEXT,
    materia_descricao VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('PENDENTE', 'CONCLUIDA', 'CANCELADA')),
    data DATE DEFAULT CURRENT_DATE,
    datavencimento DATE,
    total_horas NUMERIC(10, 2),
    horas_ministradas NUMERIC(10, 2),

    -- Rastreamento
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    -- Constraints
    CONSTRAINT pendencias_materia_avaliacao_unique UNIQUE NULLS NOT DISTINCT (materia_id, avaliacao_id),
    CONSTRAINT pendencias_pelo_menos_um_status CHECK (
        status_criacao_avaliacao IS NOT NULL OR
        status_plano_aula IS NOT NULL OR
        status_plano_ensino IS NOT NULL OR
        status_avaliacao IS NOT NULL OR
        status_gabarito IS NOT NULL OR
        status_revisao IS NOT NULL OR
        status_cadastro_sgn IS NOT NULL OR
        acompanhamento_pedagogico_sgn IS NOT NULL OR
        descricao IS NOT NULL
    )
);

-- Criar índices para otimização de consultas
CREATE INDEX IF NOT EXISTS idx_pendencias_materia_id ON pendencias(materia_id);
CREATE INDEX IF NOT EXISTS idx_pendencias_avaliacao_id ON pendencias(avaliacao_id);
CREATE INDEX IF NOT EXISTS idx_pendencias_status ON pendencias(status);
CREATE INDEX IF NOT EXISTS idx_pendencias_materia_status ON pendencias(materia_id, status);
CREATE INDEX IF NOT EXISTS idx_pendencias_avaliacao_status ON pendencias(avaliacao_id, status);
CREATE INDEX IF NOT EXISTS idx_pendencias_created_at ON pendencias(created_at);
CREATE INDEX IF NOT EXISTS idx_pendencias_datavencimento ON pendencias(datavencimento);

-- Criar função para atualizar updated_at automaticamente
CREATE OR REPLACE FUNCTION update_pendencias_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Criar trigger para atualizar updated_at
DROP TRIGGER IF EXISTS trigger_pendencias_updated_at ON pendencias;
CREATE TRIGGER trigger_pendencias_updated_at
BEFORE UPDATE ON pendencias
FOR EACH ROW
EXECUTE FUNCTION update_pendencias_updated_at();

-- =============================================================================
