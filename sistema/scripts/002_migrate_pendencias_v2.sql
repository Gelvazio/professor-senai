COMMENT ON TABLE pendencias IS 'Rastreamento completo de pendências: matérias, avaliações e tarefas gerais. Um registro por matéria/avaliação com pendências, + registros de tarefas manuais.';
COMMENT ON COLUMN pendencias.id IS 'Identificador único da pendência';
COMMENT ON COLUMN pendencias.materia_id IS 'Referência para a matéria (obrigatório)';
COMMENT ON COLUMN pendencias.avaliacao_id IS 'Referência para a avaliação (opcional, apenas se a pendência é de avaliação)';
COMMENT ON COLUMN pendencias.status_criacao_avaliacao IS 'Status de pendência: criação de avaliação na matéria';
COMMENT ON COLUMN pendencias.status_plano_aula IS 'Status de pendência: plano de aula';
COMMENT ON COLUMN pendencias.status_plano_ensino IS 'Status de pendência: plano de ensino';
COMMENT ON COLUMN pendencias.status_avaliacao IS 'Status de pendência: avaliação em si';
COMMENT ON COLUMN pendencias.status_gabarito IS 'Status de pendência: gabarito da avaliação';
COMMENT ON COLUMN pendencias.status_revisao IS 'Status de pendência: revisão da avaliação';
COMMENT ON COLUMN pendencias.status_cadastro_sgn IS 'Status de pendência: cadastro no SGN';
COMMENT ON COLUMN pendencias.acompanhamento_pedagogico_sgn IS 'Status de pendência: acompanhamento pedagógico SGN';
COMMENT ON COLUMN pendencias.descricao IS 'Descrição da pendência (para tarefas manuais)';
COMMENT ON COLUMN pendencias.materia_descricao IS 'Nome da matéria associada (cópia para busca/exibição)';
COMMENT ON COLUMN pendencias.status IS 'Status geral da pendência: PENDENTE, CONCLUIDA ou CANCELADA';
COMMENT ON COLUMN pendencias.data IS 'Data de criação/registro da pendência';
COMMENT ON COLUMN pendencias.datavencimento IS 'Data de vencimento da pendência';
COMMENT ON COLUMN pendencias.total_horas IS 'Total de horas planejadas (para tarefas)';
COMMENT ON COLUMN pendencias.horas_ministradas IS 'Horas já ministradas (para tarefas)';
COMMENT ON COLUMN pendencias.created_at IS 'Timestamp de criação do registro';
COMMENT ON COLUMN pendencias.updated_at IS 'Timestamp da última atualização';

